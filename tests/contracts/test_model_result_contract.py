def valid_model_result() -> dict:
    return {
        "contract_version": "nhi.model_result.v1",
        "result_id": "model_result_power_law_001",
        "model_id": "power_law_tail",
        "model_family": "power_law",
        "model_version": "1.0.0",
        "input_hash": "1111111111111111111111111111111111111111111111111111111111111111",
        "data": {
            "alpha": atom(2.45, "calculated", unit="exponent"),
            "xmin": atom(10.0, "measured", unit="threshold"),
            "mean_defined": atom(True, "calculated"),
            "variance_defined": atom(False, "calculated"),
            "diagnostic_p_value": atom(0.32, "modeled", unit="p-value"),
            "power_law_not_rejected": atom(True, "modeled"),
        },
        "metadata": {
            "algorithm_version": "clauset_mle_v1",
            "seed": "not_applicable",
            "bootstrap_trials": 250,
            "observations_count": 500,
        },
        "limitations": [
            "Diagnostic goodness-of-fit does not prove data are generated by a power law."
        ],
    }


def test_model_result_contract_registered() -> None:
    assert "nhi.model_result.v1" in supported_contract_versions()
    schema = load_schema("nhi.model_result.v1")
    assert schema["properties"]["contract_version"]["const"] == "nhi.model_result.v1"


def test_model_result_requires_evidence_atoms_in_data() -> None:
    doc = valid_model_result()
    doc["canonical_hash"] = contract_payload_hash(doc)
    issues = validate_contract(doc)
    assert not issues, f"Validation failed with issues: {issues}"


def test_model_result_rejects_raw_primitive_in_data() -> None:
    doc = valid_model_result()
    doc["data"]["alpha"] = 2.45  # Raw primitive instead of evidence atom
    doc["canonical_hash"] = contract_payload_hash(doc)
    issues = validate_contract(doc)
    assert any(i["code"] == "EVIDENCE_ATOM_REQUIRED" for i in issues)


def test_model_result_rejects_missing_metadata() -> None:
    doc = valid_model_result()
    del doc["metadata"]
    doc["canonical_hash"] = contract_payload_hash(doc)
    issues = validate_contract(doc)
    assert any(i["code"] == "SCHEMA_REQUIRED_MISSING" for i in issues)


def test_model_result_canonical_hash_integrity() -> None:
    doc = valid_model_result()
    h1 = contract_payload_hash(doc)
    doc["metadata"]["bootstrap_trials"] = 500
    h2 = contract_payload_hash(doc)
    assert h1 != h2
